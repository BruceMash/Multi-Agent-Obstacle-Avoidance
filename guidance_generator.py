@dataclass
class SequenceGeneratorConfig:
    k_waypoints: int = 9
    step_len: float = 0.65

    cone_angle_deg: float = 75.0
    top_k: int = 32

    line_samples: int = 8

    # Top-k candidate score:
    # score = goal alignment - risk + FMM descent
    topk_w_goal: float = 0.8
    topk_w_point_risk: float = 1.3
    topk_w_line_risk: float = 2.5
    topk_w_fmm: float = 1.0

    # Final candidate cost:
    # lower is better.
    cost_w_point_risk: float = 2.5
    cost_w_line_risk: float = 5.5
    cost_w_goal: float = 0.7
    cost_w_smooth: float = 0.25
    cost_w_height: float = 0.15
    cost_w_progress: float = 0.25
    cost_w_fmm: float = 1.0

    # Stop early if close to known goal.
    goal_tolerance: float = 0.45


class KnownGoalGuidingSequenceGenerator:
    """
    Generate a local guiding waypoint sequence toward a known target.

    This performs a virtual rollout in the local frame.
    It does not imply the robot actually follows or replans at each point.
    """

    def __init__(
        self,
        field: SectorThreatField,
        fmm: FastLocalFMM2D,
        cfg: SequenceGeneratorConfig,
    ):
        self.field = field
        self.fmm = fmm
        self.cfg = cfg

    def _candidate_dirs(self, virtual_pos: np.ndarray, goal_dir: np.ndarray) -> np.ndarray:
        dirs = self.field.sector_dirs.reshape(-1, 3)
        goal_dir = normalize(goal_dir)

        goal_scores = dirs @ goal_dir
        cos_th = np.cos(np.deg2rad(self.cfg.cone_angle_deg))

        mask = goal_scores >= cos_th
        cand_dirs = dirs[mask]
        cand_goal_scores = goal_scores[mask]

        if len(cand_dirs) == 0:
            idx = np.argsort(goal_scores)[::-1][:self.cfg.top_k]
            return dirs[idx]

        scores = np.zeros(len(cand_dirs), dtype=float)

        for i, (d, gs) in enumerate(zip(cand_dirs, cand_goal_scores)):
            d = normalize(d)
            candidate = virtual_pos + self.cfg.step_len * d

            point_risk = self.fmm.query_grid_risk(candidate[:2])
            line_risk = self.fmm.query_line_risk_grid(
                virtual_pos,
                candidate,
                n_samples=self.cfg.line_samples,
            )
            fmm_score = self.fmm.query_descent_score(
                virtual_pos[:2],
                candidate[:2],
                self.cfg.step_len,
            )

            scores[i] = (
                self.cfg.topk_w_goal * gs
                - self.cfg.topk_w_point_risk * point_risk
                - self.cfg.topk_w_line_risk * line_risk
                + self.cfg.topk_w_fmm * fmm_score
            )

        if len(cand_dirs) > self.cfg.top_k:
            idx = np.argsort(scores)[::-1][:self.cfg.top_k]
            cand_dirs = cand_dirs[idx]

        return cand_dirs

    def generate(self, start_pos: np.ndarray, goal_pos: np.ndarray):
        waypoints = []
        generation_times_ms = []
        candidate_counts = []
        selected_costs = []

        virtual_pos = start_pos.astype(float).copy()
        prev_dir = normalize(goal_pos - start_pos)

        for _ in range(self.cfg.k_waypoints):
            if np.linalg.norm(goal_pos - virtual_pos) <= self.cfg.goal_tolerance:
                break

            t0 = time.perf_counter()

            goal_dir = normalize(goal_pos - virtual_pos)
            candidate_dirs = self._candidate_dirs(virtual_pos, goal_dir)

            best_cost = np.inf
            best_point = None
            best_dir = None

            for d in candidate_dirs:
                d = normalize(d)
                candidate = virtual_pos + self.cfg.step_len * d

                point_risk = self.fmm.query_grid_risk(candidate[:2])
                line_risk = self.fmm.query_line_risk_grid(
                    virtual_pos,
                    candidate,
                    n_samples=self.cfg.line_samples,
                )

                goal_cost = 1.0 - np.dot(d, goal_dir)
                smooth_cost = 1.0 - np.dot(d, prev_dir)
                height_cost = abs(candidate[2] - virtual_pos[2])
                progress = np.linalg.norm(virtual_pos - goal_pos) - np.linalg.norm(candidate - goal_pos)
                fmm_score = self.fmm.query_descent_score(
                    virtual_pos[:2],
                    candidate[:2],
                    self.cfg.step_len,
                )

                cost = (
                    self.cfg.cost_w_point_risk * point_risk
                    + self.cfg.cost_w_line_risk * line_risk
                    + self.cfg.cost_w_goal * goal_cost
                    + self.cfg.cost_w_smooth * smooth_cost
                    + self.cfg.cost_w_height * height_cost
                    - self.cfg.cost_w_progress * progress
                    - self.cfg.cost_w_fmm * fmm_score
                )

                if cost < best_cost:
                    best_cost = cost
                    best_point = candidate
                    best_dir = d

            if best_point is None:
                best_dir = goal_dir
                best_point = virtual_pos + self.cfg.step_len * best_dir
                best_cost = np.nan

            waypoints.append(best_point)
            selected_costs.append(float(best_cost))
            candidate_counts.append(len(candidate_dirs))
            generation_times_ms.append((time.perf_counter() - t0) * 1000.0)

            # Virtual rollout only: generate sequence, not actual robot motion.
            virtual_pos = best_point
            prev_dir = best_dir

        return (
            np.asarray(waypoints, dtype=float),
            generation_times_ms,
            candidate_counts,
            selected_costs,
        )


