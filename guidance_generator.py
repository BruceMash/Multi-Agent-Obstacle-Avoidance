# 5. Visualization
# ============================================================

def visualize(
    fmm: FastLocalFMM2D,
    lidar_points: np.ndarray,
    start_pos: np.ndarray,
    goal_pos: np.ndarray,
    waypoints: np.ndarray,
    cylinder_center: np.ndarray,
    cylinder_radius: float,
) -> None:
    # 2D risk + FMM arrival contours
    fig = plt.figure(figsize=(8, 6))
    ax = fig.add_subplot(111)

    im = ax.contourf(fmm.xs, fmm.ys, fmm.risk_grid, levels=30)
    plt.colorbar(im, ax=ax, label="risk")

    finite_T = np.where(np.isfinite(fmm.T), fmm.T, np.nan)
    try:
        ax.contour(fmm.xs, fmm.ys, finite_T, levels=18, linewidths=0.6, alpha=0.65)
    except Exception:
        pass

    circle = plt.Circle(
        (cylinder_center[0], cylinder_center[1]),
        cylinder_radius,
        fill=False,
        linewidth=2,
    )
    ax.add_patch(circle)

    ax.scatter(start_pos[0], start_pos[1], marker="o", s=80, label="start/current")
    ax.scatter(goal_pos[0], goal_pos[1], marker="*", s=140, label="known goal")

    if len(waypoints) > 0:
        ax.plot(
            waypoints[:, 0],
            waypoints[:, 1],
            marker="o",
            linewidth=2,
            label="generated guiding sequence",
        )

    ax.set_title("Known-goal local FMM-like guiding sequence")
    ax.set_xlabel("x [m]")
    ax.set_ylabel("y [m]")
    ax.set_aspect("equal")
    ax.legend()
    plt.tight_layout()
    plt.show()

    # 3D LiDAR + guiding sequence
    fig = plt.figure(figsize=(8, 6))
    ax = fig.add_subplot(111, projection="3d")

    sample_n = min(1400, len(lidar_points))
    idx = np.random.choice(len(lidar_points), sample_n, replace=False)
    pts = lidar_points[idx]

    ax.scatter(pts[:, 0], pts[:, 1], pts[:, 2], s=2, alpha=0.25, label="current LiDAR points")
    ax.scatter(start_pos[0], start_pos[1], start_pos[2], marker="o", s=90, label="start/current")
    ax.scatter(goal_pos[0], goal_pos[1], goal_pos[2], marker="*", s=160, label="known goal")

    if len(waypoints) > 0:
        ax.plot(
            waypoints[:, 0],
            waypoints[:, 1],
            waypoints[:, 2],
            marker="o",
            linewidth=2,
            label="guiding sequence",
        )

    ax.set_title("3D current LiDAR observation and generated guiding sequence")
    ax.set_xlabel("x [m]")
    ax.set_ylabel("y [m]")
    ax.set_zlabel("z [m]")
    ax.set_xlim(-0.5, 7.2)
    ax.set_ylim(-3.2, 3.2)
    ax.set_zlim(-1.8, 1.8)
    ax.legend()
    plt.tight_layout()
    plt.show()


