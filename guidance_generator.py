# 2. Sector probability threat field
# ============================================================

@dataclass
class SectorThreatConfig:
    n_theta: int = 36
    n_phi: int = 13
    r_max: float = 8.0

    lidar_phi_min: float = np.deg2rad(-45)
    lidar_phi_max: float = np.deg2rad(45)

    r_safe: float = 0.45
    sigma_d: float = 0.9
    sigma_r: float = 0.5
    density_alpha: float = 0.06

    # Conservative risk behind an observed obstacle in the same sector.
    rho_occl: float = 0.6


class SectorThreatField:
    """
    Sector-based local probability risk field.

    It only uses the current local LiDAR points.
    No global map, no obstacle model, no RL.
    """

    def __init__(self, cfg: SectorThreatConfig = SectorThreatConfig()):
        self.cfg = cfg

        self.theta_min = -np.pi
        self.theta_max = np.pi
        self.phi_min = -np.pi / 2
        self.phi_max = np.pi / 2

        self.dtheta = (self.theta_max - self.theta_min) / cfg.n_theta
        self.dphi = (self.phi_max - self.phi_min) / cfg.n_phi

        self.d_min = np.full((cfg.n_theta, cfg.n_phi), cfg.r_max, dtype=float)
        self.count = np.zeros((cfg.n_theta, cfg.n_phi), dtype=float)
        self.p_dist = np.zeros((cfg.n_theta, cfg.n_phi), dtype=float)
        self.p_dens = np.zeros((cfg.n_theta, cfg.n_phi), dtype=float)
        self.p_threat = np.zeros((cfg.n_theta, cfg.n_phi), dtype=float)

        self.sector_dirs = self._build_sector_dirs()

    def _build_sector_dirs(self) -> np.ndarray:
        dirs = np.zeros((self.cfg.n_theta, self.cfg.n_phi, 3), dtype=float)

        for a in range(self.cfg.n_theta):
            theta_c = self.theta_min + (a + 0.5) * self.dtheta
            for b in range(self.cfg.n_phi):
                phi_c = self.phi_min + (b + 0.5) * self.dphi
                dirs[a, b] = spherical_dir(theta_c, phi_c)

        return dirs

    def _sector_index(self, theta, phi):
        a = np.floor((theta - self.theta_min) / self.dtheta).astype(int)
        b = np.floor((phi - self.phi_min) / self.dphi).astype(int)

        a = np.clip(a, 0, self.cfg.n_theta - 1)
        b = np.clip(b, 0, self.cfg.n_phi - 1)

        return a, b

    def build_from_lidar_points(self, lidar_points: np.ndarray) -> None:
        lidar_points = np.asarray(lidar_points, dtype=float)

        self.d_min.fill(self.cfg.r_max)
        self.count.fill(0.0)
        self.p_dist.fill(0.0)
        self.p_dens.fill(0.0)
        self.p_threat.fill(0.0)

        if len(lidar_points) == 0:
            return

        r, theta, phi = cartesian_to_spherical(lidar_points)

        valid = (
            (r > 1e-6)
            & (r <= self.cfg.r_max)
            & (phi >= self.cfg.lidar_phi_min)
            & (phi <= self.cfg.lidar_phi_max)
        )

        if not np.any(valid):
            return

        a_idx, b_idx = self._sector_index(theta[valid], phi[valid])
        np.add.at(self.count, (a_idx, b_idx), 1.0)
        np.minimum.at(self.d_min, (a_idx, b_idx), r[valid])

        has_obs = self.count > 0

        dist_excess = self.d_min - self.cfg.r_safe
        self.p_dist[has_obs] = np.where(
            self.d_min[has_obs] <= self.cfg.r_safe,
            1.0,
            np.exp(-dist_excess[has_obs] / self.cfg.sigma_d),
        )

        self.p_dens = 1.0 - np.exp(-self.cfg.density_alpha * self.count)

        self.p_threat = 1.0 - (1.0 - self.p_dist) * (1.0 - self.p_dens)
        self.p_threat = np.clip(self.p_threat, 0.0, 1.0)

    def query_risk_many(self, points: np.ndarray) -> np.ndarray:
        points = np.asarray(points, dtype=float)
        if points.ndim == 1:
            points = points[None, :]

        r = np.linalg.norm(points, axis=1)
        risks = np.zeros(len(points), dtype=float)

        valid = r >= 1e-6
        if not np.any(valid):
            return risks

        pv = points[valid]
        rv = r[valid]

        theta = np.arctan2(pv[:, 1], pv[:, 0])
        phi = np.arctan2(pv[:, 2], np.sqrt(pv[:, 0] ** 2 + pv[:, 1] ** 2))

        a, b = self._sector_index(theta, phi)
        has_obs = self.count[a, b] > 0

        local_risk = np.zeros(len(pv), dtype=float)

        if np.any(has_obs):
            ah = a[has_obs]
            bh = b[has_obs]
            rh = rv[has_obs]

            d_obs = self.d_min[ah, bh]
            p_th = self.p_threat[ah, bh]

            radial = p_th * np.exp(-0.5 * ((rh - d_obs) / self.cfg.sigma_r) ** 2)
            occl = np.where(
                rh > d_obs + self.cfg.r_safe,
                self.cfg.rho_occl * p_th,
                0.0,
            )

            local_risk[has_obs] = 1.0 - (1.0 - radial) * (1.0 - occl)

        risks[valid] = np.clip(local_risk, 0.0, 1.0)
        return risks

    def query_risk(self, point: np.ndarray) -> float:
        return float(self.query_risk_many(np.asarray(point))[0])


