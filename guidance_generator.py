
"""
Known-goal fast local FMM-like guiding sequence generator.

This version is NOT an RL module.

Assumption:
    - Current local LiDAR observation is available.
    - The local target position is known.
    - We generate a guiding waypoint sequence directly in the local frame.
    - The sequence is generated by virtual rollout; it does not mean the robot has actually moved.

Pipeline:
    Current simulated LiDAR observation
        -> sector probability threat field
        -> low-resolution 2D local FMM-like arrival-time field T(x, y)
        -> risk-aware top-k sector candidate directions
        -> one-shot virtual waypoint sequence generation toward the known target

Dependencies:
    pip install numpy matplotlib
"""

import heapq
import time
from dataclasses import dataclass
from typing import Tuple, List

import numpy as np
import matplotlib.pyplot as plt


# ============================================================
# 1. Utilities
# ============================================================

def normalize(v: np.ndarray, eps: float = 1e-8) -> np.ndarray:
    v = np.asarray(v, dtype=float)
    n = np.linalg.norm(v)
    if n < eps:
        return np.zeros_like(v)
    return v / n


def cartesian_to_spherical(points: np.ndarray) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
    points = np.asarray(points, dtype=float)
    x, y, z = points[:, 0], points[:, 1], points[:, 2]

    r = np.linalg.norm(points, axis=1)
    theta = np.arctan2(y, x)
    phi = np.arctan2(z, np.sqrt(x ** 2 + y ** 2))

    return r, theta, phi


def spherical_dir(theta: float, phi: float) -> np.ndarray:
    return np.array([
        np.cos(phi) * np.cos(theta),
        np.cos(phi) * np.sin(theta),
        np.sin(phi),
    ], dtype=float)


def generate_cylinder_surface_points(
    center: np.ndarray,
    radius: float,
    height: float,
    n_theta: int = 180,
    n_z: int = 90,
) -> np.ndarray:
    """
    Generate simulated current LiDAR observation points on a cylinder surface.

    The guidance generator only receives this point cloud, not the cylinder model.
    """
    cx, cy, cz = center

    theta = np.linspace(0, 2 * np.pi, n_theta)
    z = np.linspace(cz - height / 2, cz + height / 2, n_z)
    theta_grid, z_grid = np.meshgrid(theta, z)

    x = cx + radius * np.cos(theta_grid)
    y = cy + radius * np.sin(theta_grid)

    return np.stack([x.ravel(), y.ravel(), z_grid.ravel()], axis=1)


